internal fun FlowGraphPanel.compactZoomButton(label: String, tooltip: String): JButton =
    JButton(label).apply {
        toolTipText = tooltip
        margin = Insets(2, 3, 2, 3)
        // Override the Look & Feel's standard minimum button width.
        // The +/- buttons occupy only the glyph and a small clickable inset.
        val buttonWidth = getFontMetrics(font).stringWidth(label) +
            margin.left + margin.right + 8
        val size = Dimension(buttonWidth, preferredSize.height)
        preferredSize = size
        minimumSize = size
        maximumSize = size
    }


